"""
Twilio SMS & WhatsApp Notification Tools
Uses LangChain's TwilioAPIWrapper for cleaner integration
Following: https://python.langchain.com/docs/integrations/tools/twilio/
"""

from langchain.tools import BaseTool
from pydantic import BaseModel, Field
from typing import Optional
import os

# Try to import Twilio
try:
    from langchain_community.utilities.twilio import TwilioAPIWrapper
    TWILIO_AVAILABLE = True
except ImportError:
    TWILIO_AVAILABLE = False
    print("WARNING: Twilio utilities not installed. Run: pip install langchain-community twilio")


# ==================== INPUT SCHEMAS ====================

class SendSMSInput(BaseModel):
    """Input for sending SMS messages."""
    to: str = Field(description="Recipient phone number in E.164 format (e.g., +1234567890)")
    message: str = Field(description="SMS message text (max 1600 characters)")
    from_number: Optional[str] = Field(default=None, description="Sender phone number (optional, uses TWILIO_FROM_NUMBER)")


class SendWhatsAppInput(BaseModel):
    """Input for sending WhatsApp messages."""
    to: str = Field(description="Recipient WhatsApp number in E.164 format (e.g., +1234567890)")
    message: str = Field(description="WhatsApp message text")
    from_number: Optional[str] = Field(default=None, description="Sender WhatsApp number (optional)")


class GetMessageStatusInput(BaseModel):
    """Input for checking message delivery status."""
    message_sid: str = Field(description="Twilio message SID (starts with SM or MM)")


# ==================== TWILIO WRAPPER ====================

def get_twilio_wrapper():
    """Get configured TwilioAPIWrapper"""
    if not TWILIO_AVAILABLE:
        print("❌ Twilio not available")
        return None
    
    try:
        # TwilioAPIWrapper automatically reads from environment:
        # TWILIO_ACCOUNT_SID, TWILIO_AUTH_TOKEN, TWILIO_FROM_NUMBER
        twilio = TwilioAPIWrapper()
        return twilio
    except Exception as e:
        print(f"❌ Failed to initialize Twilio: {e}")
        return None


# ==================== SMS TOOL ====================

class SendSMSTool(BaseTool):
    name: str = "send_sms"
    description: str = """Send SMS text message to patient's phone number. 
    Use for: appointment reminders, test results, discharge instructions, urgent notifications.
    Message should be clear and concise (max 1600 characters).
    
    Parameters:
    - to: Recipient phone number (E.164 format, e.g., +1234567890)
    - message: SMS text content
    - from_number: Optional sender number (defaults to TWILIO_FROM_NUMBER env var)
    """
    args_schema: type[BaseModel] = SendSMSInput
    
    def _run(self, to: str, message: str, from_number: Optional[str] = None) -> dict:
        """Send SMS message using LangChain's TwilioAPIWrapper"""
        
        try:
            # Get Twilio wrapper
            twilio = get_twilio_wrapper()
            if not twilio:
                return {
                    "success": False,
                    "error": "Twilio not configured. Check TWILIO_ACCOUNT_SID, TWILIO_AUTH_TOKEN, TWILIO_FROM_NUMBER in .env",
                    "message_sid": None
                }
            
            # Validate message length
            if len(message) > 1600:
                message = message[:1597] + "..."
                print(f"⚠️ Message truncated to 1600 characters")
            
            # Validate phone number format
            if not to.startswith('+'):
                return {
                    "success": False,
                    "error": f"Invalid phone number: {to}. Must use E.164 format (e.g., +1234567890)",
                    "message_sid": None
                }
            
            # Send SMS using TwilioAPIWrapper
            # Correct signature: run(body: str, to: str)
            print(f"📱 Sending SMS to {to}...")
            result = twilio.run(body=message, to=to)
            
            # Parse result - TwilioAPIWrapper returns message SID on success (starts with SM)
            # or error message on failure
            if result and result.startswith('SM'):
                return {
                    "success": True,
                    "message": "SMS sent successfully",
                    "to": to,
                    "message_sid": result,  # Actual Twilio message SID
                    "status": "sent"
                }
            elif "successfully" in result.lower() or "sent" in result.lower():
                return {
                    "success": True,
                    "message": result,
                    "to": to,
                    "message_sid": "Generated by Twilio",
                    "status": "sent"
                }
            else:
                return {
                    "success": False,
                    "error": result,
                    "message_sid": None
                }
            
        except Exception as e:
            error_msg = str(e)
            print(f"❌ SMS send error: {error_msg}")
            
            # Handle common errors
            if "unverified" in error_msg.lower():
                return {
                    "success": False,
                    "error": f"Phone number {to} not verified in Twilio trial account. Verify it in console.",
                    "message_sid": None
                }
            else:
                return {
                    "success": False,
                    "error": error_msg,
                    "message_sid": None
                }


# ==================== WHATSAPP TOOL ====================

class SendWhatsAppTool(BaseTool):
    name: str = "send_whatsapp"
    description: str = """Send WhatsApp message to patient. 
    Use for: rich notifications with formatting, appointment details, test results with links.
    Supports text formatting and longer messages than SMS.
    
    Parameters:
    - to: Recipient phone number (E.164 format, e.g., +1234567890)
    - message: WhatsApp text content (supports *bold*, _italic_ formatting)
    - from_number: Optional sender number (defaults to TWILIO_FROM_NUMBER)
    """
    args_schema: type[BaseModel] = SendWhatsAppInput
    
    def _run(self, to: str, message: str, from_number: Optional[str] = None) -> dict:
        """Send WhatsApp message using TwilioAPIWrapper"""
        
        try:
            # Get Twilio wrapper
            twilio = get_twilio_wrapper()
            if not twilio:
                return {
                    "success": False,
                    "error": "Twilio not configured",
                    "message_sid": None
                }
            
            # Format recipient (WhatsApp format)
            recipient = f"whatsapp:{to}" if not to.startswith('whatsapp:') else to
            
            # Validate phone number format
            number_part = recipient.replace('whatsapp:', '')
            if not number_part.startswith('+'):
                return {
                    "success": False,
                    "error": f"Invalid phone number: {to}. Must use E.164 format (e.g., +1234567890)",
                    "message_sid": None
                }
            
            # Send WhatsApp using TwilioAPIWrapper
            # Correct signature: run(body: str, to: str)
            print(f"💬 Sending WhatsApp to {to}...")
            result = twilio.run(body=message, to=recipient)
            
            # Parse result - returns message SID (starts with MM for WhatsApp) on success
            if result and (result.startswith('MM') or result.startswith('SM')):
                return {
                    "success": True,
                    "message": "WhatsApp sent successfully",
                    "to": to,
                    "message_sid": result,  # Actual Twilio message SID
                    "status": "sent"
                }
            elif "successfully" in result.lower() or "sent" in result.lower():
                return {
                    "success": True,
                    "message": result,
                    "to": to,
                    "message_sid": "Generated by Twilio",
                    "status": "sent"
                }
            else:
                return {
                    "success": False,
                    "error": result,
                    "message_sid": None
                }
            
        except Exception as e:
            error_msg = str(e)
            print(f"❌ WhatsApp send error: {error_msg}")
            
            # Handle common errors
            if "sandbox" in error_msg.lower():
                return {
                    "success": False,
                    "error": f"Join WhatsApp sandbox first. Send 'join <code>' to Twilio WhatsApp number.",
                    "message_sid": None
                }
            else:
                return {
                    "success": False,
                    "error": error_msg,
                    "message_sid": None
                }


# ==================== MESSAGE STATUS TOOL ====================

class GetMessageStatusTool(BaseTool):
    name: str = "get_message_status"
    description: str = """Check delivery status of sent SMS or WhatsApp message.
    Use after sending important messages to confirm delivery.
    
    Parameters:
    - message_sid: Twilio message SID (starts with SM for SMS, MM for WhatsApp)
    
    Returns: delivery status, timestamps, error codes (if any)
    """
    args_schema: type[BaseModel] = GetMessageStatusInput
    
    def _run(self, message_sid: str) -> dict:
        """Check message delivery status"""
        
        try:
            # Note: TwilioAPIWrapper doesn't support status checking
            # We'll need the direct Twilio client for this
            from twilio.rest import Client
            
            account_sid = os.getenv('TWILIO_ACCOUNT_SID')
            auth_token = os.getenv('TWILIO_AUTH_TOKEN')
            
            if not account_sid or not auth_token:
                return {
                    "success": False,
                    "error": "Twilio credentials not configured"
                }
            
            client = Client(account_sid, auth_token)
            
            # Fetch message
            message = client.messages(message_sid).fetch()
            
            return {
                "success": True,
                "message_sid": message.sid,
                "status": message.status,
                "to": message.to,
                "from": message.from_,
                "error_code": message.error_code,
                "error_message": message.error_message,
                "date_sent": str(message.date_sent) if message.date_sent else None,
                "date_updated": str(message.date_updated) if message.date_updated else None,
                "price": message.price,
                "price_unit": message.price_unit,
                "num_segments": message.num_segments
            }
            
        except Exception as e:
            error_msg = str(e)
            print(f"❌ Status check error: {error_msg}")
            
            return {
                "success": False,
                "error": error_msg,
                "message_sid": message_sid
            }


